/**
 * 貼給客戶的簽署訊息——**只放簽署連結，不放帳號**。
 *
 * 舊版把匯款資訊一起附在這封訊息裡，結果簽核只佔 1 行、匯款佔 11 行，
 * 三個 ⚠️ 兩個 💡 全在催匯款，而「簽署後」三個字夾在第四行句首最容易被跳過；
 * 還有一句「確認收到款項後才會叫料下排程」替匯款製造急迫感，簽核卻沒有對應理由。
 * 實際後果：客人還沒簽核就先匯款（老闆 2026-10-13 回報）。
 *
 * 帳號改由簽署頁在「簽署完成」後顯示（SignClient 本來就有這段）。
 * 這是結構性的擋法——拿不到帳號就不會先匯，而不是靠客人自己看懂順序。
 */
export function buildSignShareMessage(signUrl: string): string {
  return [
    "請點連結線上確認並簽署報價單 👇",
    signUrl,
    "",
    // 🔴 用字刻意與簽署頁 FAQ 一致（lib/constants.ts 的 signFaq）：兩份文件講同一件事
    // 卻用不同說法，客人會以為是兩回事（老闆 2026-11-01 指出兩邊衝突）。
    "✅ 簽署代表您確認報價單上的品項、尺寸、材質與金額都正確。",
    "✅ 簽好之後畫面會顯示訂金匯款資訊，",
    "　 也可以下載已簽署的報價單 PDF 留存。",
    "",
    // 訂製品的流程（老闆 2026-11-01 確認）：
    //   簽報價 → 匯訂金 → 內勤整理「訂製訂單」用 LINE 傳給客人核對 → 備料製作
    //   → 完成通知出貨或自取。
    // 不先講，客人收到第二份文件會以為出了什麼問題。
    "📋 收到訂金後，我們會整理一份「訂製訂單」傳給您確認，",
    "　 上面有完整的尺寸、材質與配置，",
    "　 在您確認之前都還能調整。",
    "",
    "有任何問題都可以直接在這裡問我 😊",
  ].join("\n");
}
