/**
 * 貼給客戶的簽署訊息——**只放簽署連結，不放帳號**。
 *
 * 舊版把匯款資訊一起附在這封訊息裡，結果簽核只佔 1 行、匯款佔 11 行，
 * 三個 ⚠️ 兩個 💡 全在催匯款，而「簽署後」三個字夾在第四行句首最容易被跳過；
 * 還有一句「確認收到款項後才會叫料下排程」替匯款製造急迫感，簽核卻沒有對應理由。
 * 實際後果：客人還沒簽核就先匯款（老闆 2026-10-13 回報）。
 *
 * 帳號改由簽署頁在「簽署完成」後顯示（SignClient 本來就有這段）。
 * 這是結構性的擋法——拿不到帳號就不會先匯，而不是靠客人自己看懂順序。
 */
export function buildSignShareMessage(signUrl: string): string {
  return [
    "請點連結線上確認並簽署報價單 👇",
    signUrl,
    "",
    // 「簽署＝確認內容與金額」要放在最前面：後面講到還會再有一份訂製訂單，
    // 若不先講清楚價格此刻就定了，客人會以為之後還能再談（老闆 2026-10-31）。
    "✅ 簽署代表確認這份報價的內容與金額。",
    "✅ 簽好之後畫面會顯示訂金匯款資訊，",
    "　 也可以下載已簽署的合約留存。",
    "",
    // 流程是「先簽報價代表下訂意向，之後另發一份訂製訂單核對製作細節」。
    // 不先說，客人收到第二份文件會以為出了什麼問題。
    // 寫「接下來」而不是「收到訂金後」——發送時機未定案，不要寫死讓客人等錯東西。
    "📋 接下來我們會再傳一份「訂製訂單」給您核對，",
    "　 上面是尺寸、布料、工法這些製作細節，",
    "　 確認無誤後才會安排製作。",
    "",
    "有任何問題都可以直接在這裡問我 😊",
  ].join("\n");
}
